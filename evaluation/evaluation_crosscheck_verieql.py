def load_json(path):
    with open(path, "r") as f:
        return json.load(f)

def load_csv_counterexamples(csv_paths):
    # Returns: {question_id: [counterexample_path, ...], ...}
    counterexamples = {}
    for csv_path in os.listdir(csv_paths):
        with open(os.path.join(csv_paths, csv_path), newline='') as f:
            reader = csv.DictReader(f)
            for row in reader:
                qid = row.get("question_id")
                result = row.get("verieql_res")
                cpath = row.get("counterexample_path")
                if result == INCORRECT and qid and cpath:
                    counterexamples.setdefault(qid, []).append(cpath)
    return counterexamples


def main():
    ap = argparse.ArgumentParser(
        description="Verify VeriEQL counterexamples from a CSV column containing the full block."
    )
    ap.add_argument("prediction", help="Path to the prediction.")
    ap.add_argument("verieql_csv", help="Path to the csv generated by evaluation_verieql.py")
    ap.add_argument("ce_databases", help="Path to the folder containing all the counterexample databases created by evaluation_verieql.py")
    ap.add_argument("output", help="Output CSV path.")

    args = ap.parse_args()

    counterexamples = load_csv_counterexamples(args.ce_databases)

    with open(args.verieql_csv, newline='') as infile, open(args.output, 'w', newline='') as outfile:
        reader = csv.DictReader(infile)
        fieldnames = ["question_id", "res", "verieql_res_orig", "verieql_res", "bound_size", "counterexample_path", "runtime", "output1", "output2", "generated_sql", "gold_sql"]
        writer = csv.DictWriter(outfile, fieldnames=fieldnames)
        writer.writeheader()

        for row in reader:
            question_id = row["question_id"]
            if row["res"] == "incorrect" or row["verieql_res"] == INCORRECT:
                writer.writerow(row)
            else:
                results = None
                assert(row["res"] == "correct")
                assert(row["verieql_res"] in [UNKNOWN, ERROR])
                if question_id in counterexamples:
                    for ce_path in counterexamples[question_id]:
                        results = execute_counterexample_(ce_path, "./column_name_mapping.json", "../BIRD_schemas/dev.json", args.prediction)
                        if results is None:
                            continue
                        else:
                            output1, output2 = results
                            break

                if results is not None:
                    writer.writerow({
                        "question_id": question_id,
                        "res": row["res"],
                        "verieql_res_orig": row["verieql_res_orig"],
                        "verieql_res": INCORRECT,
                        "bound_size": int(os.path.basename(ce_path).split("bound")[-1].split(".")[0]),
                        "counterexample_path": ce_path,
                        "runtime": -1,
                        "output1": output1,
                        "output2": output2,
                        "generated_sql": row["generated_sql"],
                        "gold_sql": row["gold_sql"],
                    })
                else:
                    writer.writerow(row)

if __name__ == "__main__":
    main()